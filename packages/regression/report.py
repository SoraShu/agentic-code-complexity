"""Validate saved OOF predictions and generate thesis tables without refitting."""
import argparse
import csv
import json
from pathlib import Path

import evaluate as ev
import numpy as np

LABELS = {"verified": "SWE-bench Verified", "arrow": r"\texttt{arrow-py/arrow}",
          "arrow_oracle_pass": "Arrow (oracle-pass only)",
          "arrow_errors_as_failures": "Arrow (errors as failures)"}
MODELS = {"baseline": "Baseline (mean)", "lasso": "Lasso", "xgboost": "XGBoost"}
REPORT_MODELS = {"baseline": "Baseline (mean)", "median": "Baseline (median)",
                 "lasso": "Lasso", "xgboost": "XGBoost"}


def median_predictions(y, folds):
    """Predict each saved outer test fold using only its training targets."""
    prediction = np.full(len(y), np.nan)
    for train, test in folds:
        prediction[test] = np.median(y[train])
    assert np.isfinite(prediction).all()
    return prediction


def with_median(y, predictions, folds):
    prediction = median_predictions(y, folds)
    metrics = ev.summarize(y, {**predictions, "median": prediction}, folds)
    reference = metrics["median"]["mae_mean"]
    for row in metrics.values():
        row["mae_improvement_vs_median_pct"] = 100 * (reference - row["mae_mean"]) / reference
    return prediction, metrics


def performance_row(label, model, row):
    improvements = ["---", "---"] if model in ("baseline", "median") else [
        f"${row['mae_improvement_pct']:+.1f}\\%$",
        f"${row['mae_improvement_vs_median_pct']:+.1f}\\%$",
    ]
    return [label, REPORT_MODELS[model], pm(row, "r2"), pm(row, "mae"), *improvements]


def pm(row, metric):
    return f"${row[metric + '_mean']:.3f} \\pm {row[metric + '_std']:.3f}$"


def table(caption, label, columns, headers, rows, small=False):
    return "\n".join([
        "% Generated by experiments/regression/report.py; do not edit numbers manually.",
        r"\begin{table}[!ht]", r"    \centering",
        r"    \small" if small else "",
        "    \\caption{" + caption + "}", "    \\label{" + label + "}",
        r"    \resizebox{\textwidth}{!}{%",
        r"    \begin{tabular}{@{}" + columns + "@{}}", r"        \toprule",
        "        " + " & ".join(headers) + r" \\", r"        \midrule",
        *("        " + " & ".join(row) + r" \\" for row in rows),
        r"        \bottomrule", r"    \end{tabular}", "    }", r"\end{table}", "",
    ])


def audit(directory, result):
    data = json.loads((directory / "dataset.json").read_text())
    splits = json.loads((directory / "splits.json").read_text())
    with (directory / "oof_predictions.csv").open() as file:
        rows = list(csv.DictReader(file))
    ids = [r["task_id"] for r in rows]
    assert len(ids) == len(set(ids)) == result["n"]
    assert ids == [r["task_id"] for r in data["rows"]]
    y = np.asarray([float(r["complexity"]) for r in rows])
    np.testing.assert_array_equal(y, [r["complexity"] for r in data["rows"]])
    prediction = {m: np.asarray([float(r[m]) for r in rows]) for m in MODELS}
    folds = []
    for split in splits:
        train_ids, test_ids = set(split["train_ids"]), set(split["test_ids"])
        assert not train_ids & test_ids and train_ids | test_ids == set(ids)
        for inner in split["inner_splits"]:
            a, b = set(inner["train_ids"]), set(inner["validation_ids"])
            assert not a & b and a | b == train_ids and not (a | b) & test_ids
        train = np.asarray([i for i, task in enumerate(ids) if task in train_ids])
        test = np.asarray([i for i, task in enumerate(ids) if task in test_ids])
        assert all(int(rows[i]["outer_fold"]) == split["fold"] for i in test)
        np.testing.assert_allclose(prediction["baseline"][test], y[train].mean(), rtol=0, atol=1e-14)
        lasso = result["model_folds"]["lasso"][split["fold"] - 1]
        X = np.asarray([r["features"] for r in data["rows"]], dtype=float)
        median = np.nanmedian(X[train], axis=0)
        imputed = np.where(np.isnan(X[train]), median, X[train])
        for model in ("lasso", "xgboost"):
            detail = result["model_folds"][model][split["fold"] - 1]
            if "imputer_statistics" in detail:
                np.testing.assert_allclose(detail["imputer_statistics"], median)
                np.testing.assert_array_equal(detail["training_missing_counts"], np.isnan(X[train]).sum(axis=0))
        np.testing.assert_allclose(lasso["scaler_mean"], imputed.mean(axis=0))
        assert lasso["scaler_n_samples"] == len(train)
        folds.append((train, test))
    assert sorted(i for _, test in folds for i in test) == list(range(len(ids)))
    recomputed = ev.summarize(y, prediction, folds)
    for model in MODELS:
        for metric in ["r2_mean", "r2_std", "mae_mean", "mae_std", "mae_improvement_pct"]:
            np.testing.assert_allclose(recomputed[model][metric], result["metrics"][model][metric], rtol=0, atol=1e-12)
    return rows, y, prediction, folds


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("result_dir", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = args.result_dir.resolve()
    folders = [root] if (root/"results.json").exists() else sorted(p.parent for p in root.glob("*/results.json"))
    if not folders:
        raise FileNotFoundError(f"No saved results in {root}")
    args.output.mkdir(parents=True, exist_ok=False)
    rows, summaries = [], {}
    for folder in folders:
        result = json.loads((folder/"results.json").read_text())
        _, y, predictions, folds = audit(folder, result)
        _, metrics = with_median(y, predictions, folds)
        name = folder.name
        summaries[name] = metrics
        for model in REPORT_MODELS:
            rows.append(performance_row(LABELS.get(name,name), model, metrics[model]))
    (args.output/"performance.tex").write_text(table(
        r"Nested 5-by-5 CV performance. Values are the unweighted mean $\pm$ population standard deviation across outer test folds. Constant baselines use training-fold means or medians.",
        "tab:reg-perf", "llrrrr", ["Dataset", "Model", r"Outer $R^2$", "Outer MAE", "vs mean", "vs median"], rows, True))
    (args.output/"metrics.json").write_text(json.dumps(summaries,indent=2)+"\n")
    print(args.output)


if __name__ == "__main__":
    main()
